// Inlines the Vite build into one HTML file, gzips it and writes the C header
// the hub firmware serves (firmware/hub/src/web/app_gz.h). Fails if the
// bundle is over budget (plan: <= 60 KB gzipped).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const BUDGET = 60 * 1024;
const dist = new URL('../dist/', import.meta.url).pathname;
let html = readFileSync(join(dist, 'index.html'), 'utf8');
const assets = join(dist, 'assets');
for (const f of readdirSync(assets)) {
  const body = readFileSync(join(assets, f), 'utf8');
  if (f.endsWith('.js')) {
    html = html.replace(new RegExp(`<script[^>]*src="/assets/${f}"[^>]*></script>`),
      () => `<script type="module">${body.replace(/<\/script/g, '<\\/script')}</script>`);
  } else if (f.endsWith('.css')) {
    html = html.replace(new RegExp(`<link[^>]*href="/assets/${f}"[^>]*>`), () => `<style>${body}</style>`);
  }
}
const gz = gzipSync(Buffer.from(html), { level: 9 });
const etag = createHash('sha1').update(gz).digest('hex').slice(0, 16);
const bytes = [];
for (let i = 0; i < gz.length; i += 24) bytes.push('  ' + Array.from(gz.subarray(i, i + 24)).join(',') + ',');
const out = `// GENERATED by web/scripts/embed.mjs (npm run build). Do not edit.
#pragma once
#include <stddef.h>
#include <stdint.h>
#define APP_ETAG "\\"${etag}\\""
static const uint8_t APP_GZ[] = {
${bytes.join('\n')}
};
static const size_t APP_GZ_LEN = sizeof(APP_GZ);
`;
writeFileSync(new URL('../../firmware/hub/src/web/app_gz.h', import.meta.url), out);
console.log(`app: ${html.length} bytes, ${gz.length} gzipped (budget ${BUDGET})`);
if (gz.length > BUDGET) {
  console.error('Bundle over budget');
  process.exit(1);
}
